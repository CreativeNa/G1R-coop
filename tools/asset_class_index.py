#!/usr/bin/env python3
"""Index which class every converted package instantiates.

Reads  extracted/json/**/*.json   (uasset2json output)
Writes sdk/assets_by_class.tsv    path, class, package folder
       sdk/classes_summary.md     class -> how many packages, with a few examples

The export's ClassIndex is a negative index into Imports; that import's ObjectName is the class.
Files above a size cap are skipped (they are meshes/textures and carry no gameplay class anyway).

Usage:  python tools\\asset_class_index.py [--max-mb 20]
"""
import collections
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
JSON_DIR = os.path.join(ROOT, "extracted", "json")
SDK = os.path.join(ROOT, "sdk")


def class_of(path, max_bytes):
    try:
        if os.path.getsize(path) > max_bytes:
            return "(too large)"
        with open(path, "r", encoding="utf-8", errors="replace") as f:
            data = json.load(f)
    except Exception as ex:
        return "(unreadable: %s)" % type(ex).__name__
    exports = data.get("Exports") or []
    imports = data.get("Imports") or []
    if not exports:
        return "(no exports)"
    def cls_name(e):
        idx = e.get("ClassIndex", 0)
        if isinstance(idx, int) and idx < 0:
            pos = -idx - 1
            if 0 <= pos < len(imports):
                return imports[pos].get("ObjectName") or "(unnamed)"
        return "(export %s)" % idx

    stem = os.path.splitext(os.path.basename(path))[0]
    # 1. a generated class in the package means it is a blueprint of some kind
    for e in exports:
        cn = cls_name(e)
        if cn == "WidgetBlueprintGeneratedClass":
            return "WidgetBlueprint"
        if cn == "AnimBlueprintGeneratedClass":
            return "AnimBlueprint"
        if cn == "BlueprintGeneratedClass":
            return "Blueprint"
    # 2. otherwise the export named like the package
    for e in exports:
        if e.get("ObjectName") == stem:
            return cls_name(e)
    # 3. otherwise the biggest export
    return cls_name(max(exports, key=lambda e: e.get("SerialSize") or 0))


def main():
    max_mb = 20
    argv = sys.argv[1:]
    if "--max-mb" in argv:
        max_mb = int(argv[argv.index("--max-mb") + 1])
    max_bytes = max_mb * 1024 * 1024

    files = []
    for dirpath, _d, names in os.walk(JSON_DIR):
        for n in names:
            if n.endswith(".json"):
                files.append(os.path.join(dirpath, n))
    files.sort()
    if not files:
        sys.exit("no JSON under extracted/json - run uasset2json first")

    rows = []
    by_class = collections.Counter()
    examples = collections.defaultdict(list)
    for i, path in enumerate(files):
        cls = class_of(path, max_bytes)
        rel = os.path.relpath(path, JSON_DIR).replace("\\", "/")
        rows.append((rel, cls))
        by_class[cls] += 1
        if len(examples[cls]) < 3:
            examples[cls].append(rel)
        if (i + 1) % 500 == 0:
            print("%d/%d" % (i + 1, len(files)))

    os.makedirs(SDK, exist_ok=True)
    with open(os.path.join(SDK, "assets_by_class.tsv"), "w", encoding="utf-8", newline="\n") as f:
        f.write("path\tclass\n")
        for rel, cls in rows:
            f.write("%s\t%s\n" % (rel, cls))

    md = ["# Packages by class", "",
          "Which class each converted package instantiates, from the export's ClassIndex.",
          "Full list: `sdk/assets_by_class.tsv`. Generated by `tools/asset_class_index.py`.", "",
          "| class | packages | examples |", "|---|---|---|"]
    for cls, n in by_class.most_common(80):
        ex = ", ".join("`%s`" % os.path.basename(e) for e in examples[cls])
        md.append("| `%s` | %d | %s |" % (cls, n, ex))
    with open(os.path.join(SDK, "classes_summary.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(md))

    print("packages: %d, distinct classes: %d" % (len(rows), len(by_class)))
    print("written : sdk/assets_by_class.tsv, sdk/classes_summary.md")


if __name__ == "__main__":
    main()

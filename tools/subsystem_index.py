#!/usr/bin/env python3
"""Build a subsystem map of Gothic 1 Remake from the reflection SDK tables.

Reads  sdk/classes.tsv, sdk/functions.tsv, sdk/props.tsv
Writes sdk/subsystems.md

The SDK has ~48k classes; nobody can read that as a list. This groups the game's own code
(/Script/G1R and the script packages) by subsystem keyword and reports, per subsystem, the
classes that carry the most members plus the function names that look like entry points.
It is an index, not an analysis: it tells you where to open the SDK.

Usage:  python tools\\subsystem_index.py
"""
import collections
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SDK = os.path.join(ROOT, "sdk")

# subsystem -> keywords matched against class and function names
SUBSYSTEMS = [
    ("Combat / GAS", ["Damage", "GameplayEffect", "GameplayAbility", "AbilityTask", "Hit", "Weapon", "Attack", "Combat", "Armor"]),
    ("Dialogue", ["Conversation", "Topic", "Dialog", "Subtitle", "Voice"]),
    ("Story / Quests", ["Quest", "Story", "Chapter", "Journal", "Objective"]),
    ("Inventory / Items", ["Inventory", "Item", "Container", "Loot", "Trade", "Recipe", "Craft"]),
    ("Save / Load", ["Save", "Persist", "Serialize"]),
    ("AI / Behaviour", ["AI", "Behavior", "Behaviour", "Perception", "Nav", "Spawn", "Patrol"]),
    ("Magic / Spells", ["Spell", "Rune", "Magic", "Scroll", "Cast"]),
    ("Character / Stats", ["Character", "Stats", "Health", "Attribute", "Skill", "Level"]),
    ("World / Streaming", ["World", "Streaming", "Level", "Region", "Weather", "Time"]),
    ("Animation", ["Anim", "Montage", "Pose", "Skeleton", "Bone"]),
    ("UI / HUD", ["Widget", "HUD", "Menu", "UI", "Screen"]),
    ("Audio", ["Audio", "Sound", "Music", "FMOD"]),
]

GAME_PACKAGES = ("/Script/G1R", "/Script/Angelscript", "/Script/THQGDS", "/Script/AlkimiaStoryFileImport")


def load():
    classes = {}
    with open(os.path.join(SDK, "classes.tsv"), "r", encoding="utf-8") as f:
        next(f)
        for line in f:
            name, kind, sup, pkg, nprops, nfns = line.rstrip("\n").split("\t")
            classes[name] = dict(kind=kind, super=sup, pkg=pkg, props=int(nprops), fns=int(nfns))
    fns = collections.defaultdict(list)
    with open(os.path.join(SDK, "functions.tsv"), "r", encoding="utf-8") as f:
        next(f)
        for line in f:
            cls, fn = line.rstrip("\n").split("\t")
            fns[cls].append(fn)
    return classes, fns


def main():
    if not os.path.isfile(os.path.join(SDK, "classes.tsv")):
        sys.exit("sdk/classes.tsv not found - run tools/sdk_from_dump.py first")
    classes, fns = load()

    out = ["# Subsystem map", "",
           "Generated by `tools/subsystem_index.py` from the reflection SDK.",
           "Only the game's own packages are considered (%s)." % ", ".join("`%s`" % p for p in GAME_PACKAGES),
           "The column *members* is properties + functions, i.e. how much a class carries.", ""]

    for title, words in SUBSYSTEMS:
        hits = []
        for name, c in classes.items():
            if c["pkg"] not in GAME_PACKAGES:
                continue
            low = name.lower()
            if any(w.lower() in low for w in words):
                hits.append((c["props"] + c["fns"], name, c))
        if not hits:
            continue
        hits.sort(reverse=True)
        out.append("## %s" % title)
        out.append("")
        out.append("Classes: %d" % len(hits))
        out.append("")
        out.append("| class | package | props | fns | super |")
        out.append("|---|---|---|---|---|")
        for _score, name, c in hits[:12]:
            out.append("| `%s` | %s | %d | %d | `%s` |" % (name, c["pkg"], c["props"], c["fns"], c["super"]))
        # entry-point looking functions from the top classes
        fnames = []
        for _score, name, _c in hits[:40]:
            for fn in fns.get(name, []):
                if any(w.lower() in fn.lower() for w in words):
                    fnames.append("%s::%s" % (name, fn))
        if fnames:
            out.append("")
            out.append("Functions that look like entry points (first 25):")
            out.append("")
            for fn in fnames[:25]:
                out.append("* `%s`" % fn)
        out.append("")

    with open(os.path.join(SDK, "subsystems.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print("written: %s (%d bytes)" % (os.path.join(SDK, "subsystems.md"), os.path.getsize(os.path.join(SDK, "subsystems.md"))))


if __name__ == "__main__":
    main()
